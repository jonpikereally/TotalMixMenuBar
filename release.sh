#!/bin/zsh
# Build a release: universal (Apple Silicon + Intel) app with an installer,
# written to updates/MixBar.zip + updates/latest.json. Committing and
# pushing updates/ ships it: every installed copy's "Check for Updates" reads
# latest.json from this repo on GitHub.
#
# Usually you don't run this yourself: bump VERSION, write the notes in
# RELEASE_NOTES.txt, and merge to main. .github/workflows/release.yml then runs
# this on a Mac and commits updates/. To ship by hand instead:
#   UPDATE_NOTES="What changed" ./release.sh
# (without UPDATE_NOTES the notes come from RELEASE_NOTES.txt)
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'MB-[0-9]{3}' Sources/MixBar/*.swift release.sh | sort -u | while read -r c; do
  grep -q "^| $c |" ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/jonpikereally/TotalMixMenuBar/main/updates/latest.json}"
cat > Sources/MixBar/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/mixbar-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/MixBar-arm64" Sources/MixBar/*.swift
echo "Building x86_64…"
swiftc -O -target x86_64-apple-macos13 -module-cache-path "$CACHE-x86" \
  -o "$CACHE/MixBar-x86_64" Sources/MixBar/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/MixBar/MixBar.app"
mkdir -p "$APP/Contents/MacOS"
lipo -create -output "$APP/Contents/MacOS/MixBar" \
  "$CACHE/MixBar-arm64" "$CACHE/MixBar-x86_64"
cp Resources/Info.plist "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

cat > "$DIST/MixBar/Install MixBar.command" <<'INSTALL'
#!/bin/bash
# MixBar installer — copies the app to ~/Applications and launches it.
cd "$(dirname "$0")"
fail() {
  echo
  echo "Error $1: $2"
  echo "Look up this code on the MixBar error list:"
  echo "  https://github.com/jonpikereally/TotalMixMenuBar/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing MixBar…"
mkdir -p ~/Applications || fail MB-601 "Couldn't create ~/Applications."
rm -rf ~/Applications/MixBar.app
ditto --norsrc MixBar.app ~/Applications/MixBar.app \
  || fail MB-601 "Couldn't copy MixBar into ~/Applications."
# Clear the download quarantine and re-sign locally so macOS trusts it on this Mac.
xattr -dr com.apple.quarantine ~/Applications/MixBar.app 2>/dev/null
codesign --force --sign - ~/Applications/MixBar.app 2>/dev/null \
  || fail MB-602 "Couldn't sign MixBar for this Mac."
open ~/Applications/MixBar.app \
  || fail MB-603 "MixBar was installed but couldn't be opened. Open it from ~/Applications yourself."
echo
echo "Done! Look for the sliders icon in your menu bar."
echo "Grant the Accessibility permission when asked — that lets the volume"
echo "keys control TotalMix. In TotalMix, set OSC to Global OSC (see README.txt)."
INSTALL
chmod +x "$DIST/MixBar/Install MixBar.command"

cat > "$DIST/MixBar/README.txt" <<README
MixBar v$VERSION — menu bar control for RME TotalMix FX on macOS (13+)
https://github.com/jonpikereally/TotalMixMenuBar

INSTALL
1. Double-click "Install MixBar.command".
   If macOS blocks it: right-click it, choose Open, then Open again.
2. Grant the Accessibility permission when prompted (System Settings →
   Privacy & Security → Accessibility). This lets the volume keys
   control TotalMix.

SET UP TOTALMIX (FX 2.1 or newer)
1. Options → Settings → OSC tab. Pick a Remote Controller slot, tick In Use.
2. Port incoming 7001, port outgoing 9001, IP or Host Name 127.0.0.1.
3. Compatibility (Mode): Global OSC. Details: tick Send changes, Send status.
4. Tick Send Level Data (for the Levels window).
5. Options → Enable OSC Control must be ticked.

USE
• Click the menu bar icon: output volumes, mute, Comp/EQ, Speaker B, Dim,
  Mono, and 48V / Instrument / Comp / EQ for your inputs
• Volume keys change the chosen TotalMix output (step 1–10 dB, with a
  "never louder than" ceiling); hold Shift+Option for quarter steps
• Mute key = Dim (or mute, in Settings); Shift+Cmd+M = Mono
• Levels window: always-on-top input meters; a name turns red on clipping
  (click to reset)

PRIVACY
MixBar talks only to TotalMix on your own Mac (UDP, 127.0.0.1). No
accounts, no analytics. The only thing it fetches from the internet is a
small version file from the GitHub repo above, to see whether an update
exists.
README

mkdir -p updates
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent MixBar "$OLDPWD/updates/MixBar.zip.tmp")
mv -f updates/MixBar.zip.tmp updates/MixBar.zip
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "MixBar.zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > updates/latest.json.tmp
mv -f updates/latest.json.tmp updates/latest.json

./build.sh >/dev/null
echo "Release v$VERSION written to updates/. Ship it with:"
echo "  git add -A && git commit -m \"Release v$VERSION\" && git push"
